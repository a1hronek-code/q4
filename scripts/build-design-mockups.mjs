// One-off helper: converts the static HTML files in design-mockups/ into
// isolated, noindex Next.js pages under app/navrh/{1,2,3}/page.tsx so they
// can be shared via a live q4.sk URL without affecting the real site design.
// CSS is scoped by prefixing every selector with the page's wrapper class,
// so it cannot leak into or collide with the global stylesheet.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

const pages = [
  {
    id: 1,
    file: "navrh-1-tatry.html",
    title: "Návrh 1 – Tatranský horizont",
    wrapper: "navrh1",
  },
  {
    id: 2,
    file: "navrh-2-trikolora.html",
    title: "Návrh 2 – Trikolóra Grid",
    wrapper: "navrh2",
  },
  {
    id: 3,
    file: "navrh-3-tmavy-glass.html",
    title: "Návrh 3 – Tmavý alpský glass",
    wrapper: "navrh3",
  },
];

function scopeCss(css, wrapper) {
  // Split into rule blocks while keeping comments untouched.
  return css.replace(/(^|\})\s*([^{}]+)\{/g, (match, brace, selectorList) => {
    const scoped = selectorList
      .split(",")
      .map((sel) => {
        const trimmed = sel.trim();
        if (!trimmed) return trimmed;
        if (trimmed === ":root" || trimmed === "body") return `.${wrapper}`;
        if (trimmed.startsWith("@")) return trimmed;
        return `.${wrapper} ${trimmed}`;
      })
      .join(",\n");
    return `${brace}\n${scoped}{`;
  });
}

for (const page of pages) {
  const html = readFileSync(path.join(root, "design-mockups", page.file), "utf8");
  const styleMatch = html.match(/<style>([\s\S]*?)<\/style>/);
  const bodyMatch = html.match(/<body>([\s\S]*?)<\/body>/);
  if (!styleMatch || !bodyMatch) {
    throw new Error(`Could not parse ${page.file}`);
  }
  const scopedCss = scopeCss(styleMatch[1], page.wrapper);
  const bodyHtml = bodyMatch[1].trim();

  const tsx = `import type { Metadata } from "next";

// Static visual mockup — not linked from navigation, excluded from indexing.
// Generated by scripts/build-design-mockups.mjs from design-mockups/${page.file}.
export const metadata: Metadata = {
  title: "${page.title} | Q4.sk návrh",
  robots: { index: false, follow: false },
};

const css = \`${scopedCss.replace(/`/g, "\\`")}\`;

const bodyHtml = \`${bodyHtml.replace(/`/g, "\\`")}\`;

export default function Page() {
  return (
    <div className="${page.wrapper}">
      <style dangerouslySetInnerHTML={{ __html: css }} />
      <div dangerouslySetInnerHTML={{ __html: bodyHtml }} />
    </div>
  );
}
`;

  writeFileSync(path.join(root, "app", "navrh", String(page.id), "page.tsx"), tsx, "utf8");
  console.log(`Wrote app/navrh/${page.id}/page.tsx`);
}
